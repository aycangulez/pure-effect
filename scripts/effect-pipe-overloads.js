// @ts-check

/**
 * Generates `effectPipe`'s overloads in index.d.ts, one per pipeline length, and writes them between the
 * markers there. Run `npm run generate` after editing this file; a test fails when index.d.ts and this
 * output differ, so the overloads are never edited by hand.
 *
 * Every overload has one shape: the input `T0`, then `R1` to `Rn`, each step's whole return. Each step
 * receives `EffectValue` of the one before, and the pipeline fails with every step's `EffectError` and
 * reads every step's `EffectContext`. Inferring the return whole joins Failures of different shapes into a
 * union, where one error parameter per step picked one of them and refused the rest. A step that cannot
 * fail adds `never` to the error, and one that reads no context adds `unknown` to the intersection. Each
 * `Rn` defaults to `never`, which reads as no value, no error and an `unknown` context, for a step typed
 * `any` that leaves nothing to infer.
 */

import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath, pathToFileURL } from 'node:url';
import * as prettier from 'prettier';

/** The longest pipeline typed without nesting. Past it a call is a compile error; see DESIGN.md. */
export const MAX_STEPS = 20;

export const BEGIN =
    '// BEGIN effectPipe overloads, generated by scripts/effect-pipe-overloads.js: edit it, then npm run generate.';
export const END = '// END effectPipe overloads.';

const declarationsPath = fileURLToPath(new URL('../index.d.ts', import.meta.url));

const docComment = `/**
 * Composes steps into a pipeline: each step gets the previous step's value, and a \`Failure\` stops it.
 * Typed for up to ${MAX_STEPS} steps; nest pipelines for more.
 */`;

/** `[1, 2, ..., n]` */
const upTo = (/** @type {number} */ n) => Array.from({ length: n }, (_, i) => i + 1);

/** The overload for a pipeline of `n` steps, on one line; Prettier lays it out. */
const overload = (/** @type {number} */ n) => {
    const steps = upTo(n);
    const typeParameters = ['T0', ...steps.map((i) => `R${i} extends AnyEffect = never`)];
    const input = (/** @type {number} */ i) => (i === 1 ? 'T0' : `EffectValue<R${i - 1}>`);
    const parameters = steps.map((i) => `f${i}: (value: ${input(i)}) => R${i}`);
    const errors = steps.map((i) => `EffectError<R${i}>`).join(' | ');
    const contexts = steps.map((i) => `EffectContext<R${i}>`).join(' & ');
    return (
        `export declare function effectPipe<${typeParameters.join(', ')}>(${parameters.join(', ')}): ` +
        `(start: T0) => Effect<EffectValue<R${n}>, ${errors}, ${contexts}>;`
    );
};

/**
 * The generated block, markers included, formatted with the repository's Prettier configuration so that
 * `npm run format` leaves it as it is.
 * @returns {Promise<string>}
 */
export async function effectPipeOverloads() {
    const source = [docComment + '\n' + overload(1), ...upTo(MAX_STEPS).slice(1).map(overload)].join('\n\n');
    const options = (await prettier.resolveConfig(declarationsPath)) ?? {};
    const formatted = await prettier.format(source, { ...options, parser: 'typescript' });
    return `${BEGIN}\n${formatted.trimEnd()}\n${END}`;
}

/**
 * The block as index.d.ts currently has it, markers included.
 * @param {string} declarations
 */
export function currentOverloads(declarations) {
    const start = declarations.indexOf(BEGIN);
    const end = declarations.indexOf(END);
    if (start === -1 || end === -1 || end < start) throw new Error(`index.d.ts has no '${BEGIN}' ... '${END}' block.`);
    return declarations.slice(start, end + END.length);
}

// Run directly, it rewrites the block in place.
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
    const declarations = await readFile(declarationsPath, 'utf8');
    const generated = await effectPipeOverloads();
    const updated = declarations.replace(currentOverloads(declarations), generated);
    if (updated === declarations) {
        console.log('index.d.ts: effectPipe overloads already up to date.');
    } else {
        await writeFile(declarationsPath, updated);
        console.log(`index.d.ts: wrote ${MAX_STEPS} effectPipe overloads.`);
    }
}
