// @ts-check

/**
 * Generates a declaration file beside the flight recorder and each example, from its JSDoc, so a TypeScript project
 * imports either typed, without `allowJs` and without type-checking the JavaScript under its own settings. Run
 * `npm run generate` after editing one; a test fails when a declaration file and this output differ, so they are
 * never edited by hand.
 */

import { readFile, writeFile } from 'node:fs/promises';
import { basename, relative } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import * as prettier from 'prettier';
import ts from 'typescript';

const root = fileURLToPath(new URL('..', import.meta.url));

/** The JavaScript files that ship with generated declarations, by path from the repository root. */
export const GENERATED = ['flight-recorder.js', 'examples/opentelemetry-example.js'];

/**
 * The declaration file for each of `GENERATED`, keyed by its path from the repository root.
 * @returns {Promise<Map<string, string>>}
 */
export async function jsDeclarations() {
    /** @type {Map<string, string>} */
    const emitted = new Map();
    const program = ts.createProgram(
        GENERATED.map((file) => `${root}${file}`),
        {
            allowJs: true,
            declaration: true,
            emitDeclarationOnly: true,
            rootDir: root,
            outDir: root,
            skipLibCheck: true,
            target: ts.ScriptTarget.ES2022,
            module: ts.ModuleKind.NodeNext,
            moduleResolution: ts.ModuleResolutionKind.NodeNext
        }
    );
    const result = program.emit(undefined, (name, text) => void emitted.set(relative(root, name), text));
    const errors = result.diagnostics.map((d) => ts.flattenDiagnosticMessageText(d.messageText, ' '));
    if (errors.length > 0) throw new Error(`The declarations did not emit: ${errors.join('; ')}`);
    const options = (await prettier.resolveConfig(`${root}index.d.ts`)) ?? {};
    /** @type {Map<string, string>} */
    const declarations = new Map();
    for (const file of GENERATED) {
        const path = file.replace(/\.js$/, '.d.ts');
        const text = emitted.get(path);
        if (text === undefined) throw new Error(`No declarations were emitted for ${file}.`);
        const header = `// Generated by scripts/js-declarations.js from ${basename(file)}: edit its JSDoc, then run npm run generate.\n`;
        declarations.set(path, await prettier.format(header + text, { ...options, parser: 'typescript' }));
    }
    return declarations;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
    for (const [path, generated] of await jsDeclarations()) {
        const current = await readFile(`${root}${path}`, 'utf8').catch(() => '');
        if (generated === current) {
            console.log(`${path}: already up to date.`);
        } else {
            await writeFile(`${root}${path}`, generated);
            console.log(`${path}: written.`);
        }
    }
}
