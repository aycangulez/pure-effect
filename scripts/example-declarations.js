// @ts-check

/**
 * Generates a declaration file beside each example, from the example's JSDoc, so a TypeScript project that copies an
 * example imports it typed, without `allowJs` and without type-checking the copy under its own settings. Run
 * `npm run generate` after editing an example; a test fails when a declaration file and this output differ, so they
 * are never edited by hand.
 */

import { readFile, writeFile } from 'node:fs/promises';
import { basename } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import * as prettier from 'prettier';
import ts from 'typescript';

const root = fileURLToPath(new URL('..', import.meta.url));

/** The examples that ship, by file name in examples/. */
export const EXAMPLES = ['opentelemetry-example.js', 'recording-example.js'];

/**
 * The declaration file for each example, keyed by its file name in examples/.
 * @returns {Promise<Map<string, string>>}
 */
export async function exampleDeclarations() {
    /** @type {Map<string, string>} */
    const emitted = new Map();
    const program = ts.createProgram(
        EXAMPLES.map((file) => `${root}examples/${file}`),
        {
            allowJs: true,
            declaration: true,
            emitDeclarationOnly: true,
            rootDir: root,
            outDir: `${root}examples`,
            skipLibCheck: true,
            target: ts.ScriptTarget.ES2022,
            module: ts.ModuleKind.NodeNext,
            moduleResolution: ts.ModuleResolutionKind.NodeNext
        }
    );
    const result = program.emit(undefined, (name, text) => void emitted.set(basename(name), text));
    const errors = result.diagnostics.map((d) => ts.flattenDiagnosticMessageText(d.messageText, ' '));
    if (errors.length > 0) throw new Error(`The examples' declarations did not emit: ${errors.join('; ')}`);
    const options = (await prettier.resolveConfig(`${root}index.d.ts`)) ?? {};
    /** @type {Map<string, string>} */
    const declarations = new Map();
    for (const file of EXAMPLES) {
        const name = file.replace(/\.js$/, '.d.ts');
        const text = emitted.get(name);
        if (text === undefined) throw new Error(`No declarations were emitted for ${file}.`);
        const header = `// Generated by scripts/example-declarations.js from ${file}: edit its JSDoc, then run npm run generate.\n`;
        declarations.set(name, await prettier.format(header + text, { ...options, parser: 'typescript' }));
    }
    return declarations;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
    for (const [name, generated] of await exampleDeclarations()) {
        const path = `${root}examples/${name}`;
        const current = await readFile(path, 'utf8').catch(() => '');
        if (generated === current) {
            console.log(`examples/${name}: already up to date.`);
        } else {
            await writeFile(path, generated);
            console.log(`examples/${name}: written.`);
        }
    }
}
